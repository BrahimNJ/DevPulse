// PreToolUse hook: stops agents from hand-editing files that are secret or generated.
import { projectRelativePath, readHookInput } from './hook-input.mjs';

/** @type {ReadonlyArray<{ pattern: RegExp, reason: string }>} */
const PROTECTED = [
  { pattern: /(^|\/)\.env(\..+)?$/, reason: 'environment files may hold secrets' },
  { pattern: /^package-lock\.json$/, reason: 'the lockfile is generated by npm install' },
  { pattern: /^CHANGELOG\.md$/, reason: 'the changelog is generated by release-please' },
  { pattern: /^\.release-please-manifest\.json$/, reason: 'versions are set by release-please' },
  { pattern: /^\.git\//, reason: 'Git internals must only change through git commands' },
  { pattern: /^\.husky\/_\//, reason: 'husky generates this directory' },
];

const input = await readHookInput();
const path = projectRelativePath(input);
const match = path === undefined ? undefined : PROTECTED.find(({ pattern }) => pattern.test(path));

if (path !== undefined && match !== undefined) {
  // Exit code 2 blocks the tool call and returns stderr to Claude as the reason.
  console.error(`Blocked edit of ${path}: ${match.reason}.`);
  process.exit(2);
}
