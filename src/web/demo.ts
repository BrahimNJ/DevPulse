/** A release about every ten days over the year, alternating two release lines. */
function demoReleases(): DeliveryReportResponse['releases']['recent'] {
  return Array.from({ length: 36 }, (_, index) => ({
    tag:
      index % 2 === 0 ? `v25.${String(18 - index / 2)}.0` : `v24.${String(30 - (index - 1) / 2)}.0`,
    publishedAt: new Date(Date.parse(GENERATED) - (2 + index * 10) * DAY_MS).toISOString(),
  }));
}

