import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import type { BranchReportResponse } from './api.ts';
import { branchReportMarkdown } from './export-branches.ts';
import { messagesFor } from './i18n.ts';

const REPORT: BranchReportResponse = {
  repository: 'acme/rocket_ship',
  defaultBranch: 'main',
  generatedAt: '2026-11-09T10:00:00.000Z',
  staleDays: 90,
  totals: { branches: 2, protected: 1, stale: 1 },
  branches: [
    {
      name: 'main',
      isProtected: true,
      isDefault: true,
      isStale: false,
      ageDays: 2,
      divergence: null,
      lastCommit: { sha: 'a1', date: '2026-11-07T10:00:00.000Z', author: 'ada' },
    },
    {
      name: 'old|work',
      isProtected: false,
      isDefault: false,
      isStale: true,
      ageDays: 120,
      divergence: { ahead: 3, behind: 40 },
      lastCommit: { sha: 'b2', date: '2026-07-12T10:00:00.000Z', author: null },
    },
  ],
};

function english(report: BranchReportResponse = REPORT): string {
  return branchReportMarkdown(report, messagesFor('en'), 'en');
}

function french(report: BranchReportResponse = REPORT): string {
  return branchReportMarkdown(report, messagesFor('fr'), 'fr');
}

describe('branch report as Markdown', () => {
  it('opens with the repository, the date and the threshold', () => {
    assert.ok(english().startsWith('# acme/rocket\\_ship · Branches\n'));
    assert.ok(english().includes('Report generated by DevPulse on 9 Nov 2026.'));
    assert.ok(english().includes('Stale after 90 days.'));
  });

  it('writes the same opening in French', () => {
    assert.ok(french().includes('Rapport généré par DevPulse le 9 nov. 2026.'));
    assert.ok(french().includes('Inactive après 90 jours.'));
  });

  it('sums the branches up with the figures of the dashboard', () => {
    const text = english();
    assert.ok(text.includes('## Summary\n'));
    assert.ok(text.includes('- Branches: 2 (default main)'));
    assert.ok(text.includes('- Protected: 1 (50% of branches)'));
    assert.ok(text.includes('- Stale: 1 (no commit for 90+ days)'));
    assert.ok(text.includes('- Median age: 2\u00a0months (since the last commit)'));
  });

  it('sums up a repository without branches', () => {
    const text = english({
      ...REPORT,
      defaultBranch: null,
      totals: { branches: 0, protected: 0, stale: 0 },
      branches: [],
    });
    assert.ok(text.includes('- Branches: 0 (default none)'));
    assert.ok(text.includes('- Median age: – (since the last commit)'));
    assert.ok(text.endsWith('## Branches\n\nThis repository has no branch yet.\n'));
  });

  it('lists every branch with its figures and status', () => {
    const text = english();
    assert.ok(text.includes('| Branch | Last commit | Age | Ahead / behind | Author | Status |\n'));
    assert.ok(text.includes('| --- | --- | ---: | ---: | --- | --- |\n'));
    assert.ok(text.includes('| main | 7 Nov 2026 | 2 days | – | ada | default, protected |\n'));
  });

  it('escapes a branch name and fills in a missing author', () => {
    assert.ok(
      english().includes(
        String.raw`| old\|work | 12 Jul 2026 | 4` + ' months | +3 / −40 | – | stale |\n',
      ),
    );
  });

  it('writes the summary and the table in French', () => {
    const text = french();
    assert.ok(text.includes('| Branch | Dernier commit |'));
    assert.ok(text.includes('- Protégées\u202f: 1 (50 % des branches)'));
  });
});
