import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import type { BranchReportResponse } from './api.ts';
import { branchReportMarkdown } from './export-branches.ts';
import { messagesFor } from './i18n.ts';

const REPORT: BranchReportResponse = {
  repository: 'acme/rocket_ship',
  defaultBranch: 'main',
  generatedAt: '2026-11-09T10:00:00.000Z',
  staleDays: 90,
  totals: { branches: 2, protected: 1, stale: 1 },
  branches: [
    {
      name: 'main',
      isProtected: true,
      isDefault: true,
      isStale: false,
      ageDays: 2,
      divergence: null,
      lastCommit: { sha: 'a1', date: '2026-11-07T10:00:00.000Z', author: 'ada' },
    },
    {
      name: 'old|work',
      isProtected: false,
      isDefault: false,
      isStale: true,
      ageDays: 120,
      divergence: { ahead: 3, behind: 40 },
      lastCommit: { sha: 'b2', date: '2026-07-12T10:00:00.000Z', author: null },
    },
  ],
};

function english(report: BranchReportResponse = REPORT): string {
  return branchReportMarkdown(report, messagesFor('en'), 'en');
}

function french(report: BranchReportResponse = REPORT): string {
  return branchReportMarkdown(report, messagesFor('fr'), 'fr');
}

describe('branch report as Markdown', () => {
  it('opens with the repository, the date and the threshold', () => {
    assert.ok(english().startsWith('# acme/rocket\\_ship · Branches\n'));
    assert.ok(english().includes('Report generated by DevPulse on 9 Nov 2026.'));
    assert.ok(english().includes('Stale after 90 days.'));
  });

  it('writes the same opening in French', () => {
    assert.ok(french().includes('Rapport généré par DevPulse le 9 nov. 2026.'));
    assert.ok(french().includes('Inactive après 90 jours.'));
  });
});
